import { LESSONS } from '../src/content';
import { ZERO_LESSONS } from '../src/content/lessons-zero';
import { FOUNDATION_LESSONS } from '../src/content/lessons-foundations';
import { PLC_LESSONS } from '../src/content/lessons-plc';
import { FIELD_LESSONS } from '../src/content/lessons-field';
import { CORE2_LESSONS } from '../src/content/lessons-core2';
import { PRO_LESSONS } from '../src/content/lessons-pro';

const FILE_OF = new Map<string, string>(Object.entries({
  'lessons-zero': ZERO_LESSONS, 'lessons-foundations': FOUNDATION_LESSONS, 'lessons-plc': PLC_LESSONS,
  'lessons-field': FIELD_LESSONS, 'lessons-core2': CORE2_LESSONS, 'lessons-pro': PRO_LESSONS,
}).flatMap(([file, list]) => list.map((l) => [l.id, file] as [string, string])));

/** Source text of src/content/catalog.gen.ts, from the full lesson data. */
export function catalogSource(): string {
  const rows = LESSONS.map((l) => `  ${JSON.stringify({ id: l.id, track: l.track, title: l.title, minutes: l.minutes, summary: l.summary, task: Boolean(l.task), file: FILE_OF.get(l.id) })},`);
  return `// GENERATED by scripts/gen-catalog.ts from the lesson files — do not edit. Run: npm run catalog\nimport type { LessonMeta } from './catalog';\n\nexport const LESSON_META: LessonMeta[] = [\n${rows.join('\n')}\n];\n`;
}
