import { LESSONS } from '../src/content';

/** Source text of src/content/catalog.gen.ts, from the full lesson data. */
export function catalogSource(): string {
  const rows = LESSONS.map((l) => `  ${JSON.stringify({ id: l.id, track: l.track, title: l.title, minutes: l.minutes, summary: l.summary, task: Boolean(l.task) })},`);
  return `// GENERATED by scripts/gen-catalog.ts from the lesson files — do not edit. Run: npm run catalog\nimport type { LessonMeta } from './catalog';\n\nexport const LESSON_META: LessonMeta[] = [\n${rows.join('\n')}\n];\n`;
}
