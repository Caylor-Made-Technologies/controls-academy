// Draws the data for the poster stills (src/three/poster/data.gen.ts) from the real 3D scenes: each view is
// opened in a browser, its meshes are read as boxes/cylinders with the live camera, and the small parts are
// dropped. Run after a build with a preview on :4180:  npm run posters
import { createRequire } from 'node:module';
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
const require = createRequire(import.meta.url);
let pw;
try { pw = require('playwright'); } catch { pw = require('/opt/node-tools/node_modules/playwright'); }

const BASE = process.env.SITE_URL ?? 'http://localhost:4180/controls-academy/';
const { views } = JSON.parse(execSync('npx vite-node scripts/poster-targets.ts', { encoding: 'utf8' }).trim().split('\n').at(-1));
const SHAPES = [{ w: 375, h: 812 }, { w: 768, h: 1024 }, { w: 1440, h: 900 }];
const MAX_PRIMS = 48;

const browser = await pw.chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const out = {};
for (const shape of SHAPES) {
  const ctx = await browser.newContext({ viewport: { width: shape.w, height: shape.h }, reducedMotion: 'reduce', bypassCSP: true });
  await ctx.addInitScript(() => {
    localStorage.setItem('ca:prefs', JSON.stringify({ onboarded: true, quality: 'high', theme: 'dark' }));
    sessionStorage.setItem('ca:powered', '1');
  });
  const page = await ctx.newPage();
  for (const v of views) {
    await page.goto('about:blank');
    await page.goto(`${BASE}#/${v.route}`);
    await page.waitForSelector('canvas', { timeout: 30000 });
    await page.waitForFunction(() => { const s = window.__ca3d.stats(); return s.live > 0 && s.stages.every((x) => x.frames > 1); }, null, { timeout: 30000 });
    await page.waitForTimeout(900);
    const dumps = await page.evaluate(() => window.__ca3d.dump());
    const d = dumps.at(-1);
    const entry = (out[v.key] ??= { fov: d.fov, views: [], prims: null });
    const r3 = (a) => a.map((x) => Math.round(x * 1000) / 1000);
    entry.views.push({ aspect: Math.round(d.aspect * 100) / 100, pos: r3(d.pos), look: r3(d.look) });
    if (!entry.prims) {
      // Keep the parts that read at poster size: rank by apparent size from this camera.
      const dist = (p) => Math.hypot(p[0] / 1000 - d.pos[0], p[1] / 1000 - d.pos[1], p[2] / 1000 - d.pos[2]);
      const size = (p) => Math.max(p[3], p[4], p[5]) / 1000 / Math.max(0.05, dist(p));
      entry.prims = d.prims.filter((p) => Math.min(p[3], p[4], p[5]) >= 1 && size(p) > 0.012 && size(p) < 4)
        .sort((a, b) => size(b) - size(a)).slice(0, MAX_PRIMS);
    }
    console.log(`${v.key} @${shape.w}: ${d.prims.length} meshes → ${entry.prims.length} prims, aspect ${d.aspect.toFixed(2)}`);
  }
  await ctx.close();
}
await browser.close();

// One data file per page family, so a route only downloads the posters it can show.
const FILES = { sim: (k) => k === 'panel' || k.startsWith('m:'), wiring: (k) => k.startsWith('wiring:'), inside: (k) => k.startsWith('inside:'), meter: (k) => k.startsWith('meter:') };
for (const [name, match] of Object.entries(FILES)) {
  const body = Object.entries(out).filter(([k]) => match(k)).map(([k, e]) => `  ${JSON.stringify(k.replace(/^\w+:/, ''))}: ${JSON.stringify(e)},`).join('\n');
  writeFileSync(new URL(`../src/three/poster/${name}.gen.ts`, import.meta.url), `// Generated by scripts/gen-posters.mjs from the live 3D scenes. Do not edit by hand: run \`npm run posters\`.\nimport type { PosterSpec } from './project';\n\nexport const POSTERS: Record<string, PosterSpec> = {\n${body}\n};\n`);
}
console.log(`✓ ${Object.keys(out).length} posters written`);
